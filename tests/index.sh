#!/usr/bin/env bash
#
# The test catalog, generated from the tests themselves: each test describes itself in
# the comment it starts with (after a `#!` line), an error test also by its
# EXPECT-ERROR text, a lint test by its first EXPECT-WARNING. Prints Markdown.
#
# Usage:  tests/index.sh            print the catalog
#         tests/index.sh --check    exit 1 listing each test with no description
#                                   (run.sh runs this)
set -u
here="$(cd "$(dirname "$0")" && pwd)"

# The leading comment of $1 as one line, without the EXPECT-*/TEST-MODES markers.
describe() {
    LC_ALL=C awk '
        NR == 1 && substr($0, 1, 3) == "\357\273\277" { $0 = substr($0, 4) }
        NR == 1 && /^#!/ { next }
        /^[ \t]*\/\// {
            line = $0
            sub(/^[ \t]*\/\/[ \t]?/, "", line)
            if (line ~ /^(EXPECT-ERROR|EXPECT-WARNING|TEST-MODES)/) { next }
            text = text (text == "" ? "" : " ") line
            next
        }
        { exit }
        END { gsub(/\|/, "\\|", text); print text }
    ' "$1"
}

marker() {
    grep -m1 -o "$2:.*" "$1" | sed "s/^$2:[ ]*//; s/|/\\\\|/g"
}

check=0
[[ "${1:-}" == "--check" ]] && check=1
missing=0

section() {
    local title="$1" dir="$2" kind="$3"
    [[ $check == 0 ]] && printf '\n## %s\n\n| Test | Description |\n|------|-------------|\n' "$title"
    for esk in "$dir"/*.esk; do
        local name d m
        name="$(basename "$esk" .esk)"
        d="$(describe "$esk")"
        case "$kind" in
            run)
                if [[ -z "$d" ]]; then
                    missing=$((missing+1))
                    [[ $check == 1 ]] && echo "no description (start the test with a // comment): tests/$name.esk"
                fi
                if [[ -f "$dir/$name.expected" ]]; then m="run"; else m="smoke"; fi
                [[ $check == 0 ]] && printf '| `%s` (%s) | %s |\n' "$name" "$m" "$d" ;;
            error)
                m="$(marker "$esk" EXPECT-ERROR)"
                [[ $check == 0 ]] && printf '| `errors/%s` | %s%s |\n' "$name" "${d:+$d }" "rejected: \`$m\`" ;;
            lint)
                m="$(marker "$esk" EXPECT-WARNING)"
                [[ $check == 0 ]] && printf '| `warnings/%s` | %s%s |\n' "$name" "${d:+$d }" "${m:+warns: \`$m\`}" ;;
        esac
    done
}

[[ $check == 0 ]] && printf '# Test catalog\n\nGenerated by `tests/index.sh` from the first comment of each test.\n'
section "run and smoke tests" "$here" run
section "error tests" "$here/errors" error
section "lint tests" "$here/warnings" lint
[[ $check == 1 && $missing -gt 0 ]] && exit 1
exit 0
