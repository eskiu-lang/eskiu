#!/usr/bin/env python3
"""Write selfhost/eir_c_text.esk: the C text the EIR C99 emitter copies into its output
(the prelude of eir/eir_c.cpp, the runtime of eir/eir_runtime.cpp and its table of C
functions), as Eskiu constants, so the self-hosted emitter (selfhost/eir_c.esk) prints the
same bytes. Run it after changing either C++ file; tests/selfhost/eir_c_parity.sh checks
that the file is current.

    python3 tools/gen_eir_c_text.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def raw_string(src, name):
    m = re.search(r'const char\* ' + name + r' = R"(\w*)\((.*?)\)\1";', src, re.S)
    if not m:
        sys.exit(f"gen_eir_c_text: {name} not found")
    return m.group(2)


def lit(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) > 126:
            sys.exit(f"gen_eir_c_text: unexpected byte {ord(ch)}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    c = (ROOT / "eir/eir_c.cpp").read_text()
    rt = (ROOT / "eir/eir_runtime.cpp").read_text()
    prelude = raw_string(c, "kPrelude")
    body = raw_string(rt, "kRuntimeBody")
    table = re.search(r"const LibcFn kLibcFns\[\] = \{(.*?)\n\};", rt, re.S).group(1)
    fns = re.findall(r'\{"(\w+)",\s*"((?:[^"\\]|\\.)*)",\s*"((?:[^"\\]|\\.)*)",\s*(true|false)\}', table)
    lines = [
        "// Generated by tools/gen_eir_c_text.py from eir/eir_c.cpp and eir/eir_runtime.cpp: the",
        "// C text the EIR C99 emitter copies into its output. Do not edit; rerun the tool.",
        "",
        f"const string EC_PRELUDE = {lit(prelude)};",
        "",
        f"const string EC_RT_BODY = {lit(body)};",
        "",
        f"const int EC_NLIBC = {len(fns)};",
        f"const string[{len(fns)}] EC_LIBC_NAME = {{{', '.join(lit(f[0]) for f in fns)}}};",
        f"const string[{len(fns)}] EC_LIBC_PROTO = {{{', '.join(lit(f[1]) for f in fns)}}};",
        f"const string[{len(fns)}] EC_LIBC_CAST = {{{', '.join(lit(f[2]) for f in fns)}}};",
        f"const int[{len(fns)}] EC_LIBC_WIN = {{{', '.join('1' if f[3] == 'true' else '0' for f in fns)}}};",
        "",
    ]
    text = "\n".join(lines)
    out = ROOT / "selfhost/eir_c_text.esk"
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != text:
            sys.exit("selfhost/eir_c_text.esk is out of date: run python3 tools/gen_eir_c_text.py")
        return
    out.write_text(text)


main()
